"""Autopilot thresholds per technique tier, derived from published benchmark results (plan item 10.7).

    python -m trovebench thresholds --results bench/published/<id> ... [--out internal/autopilot/thresholds.toml]

Autopilot's trial numbers were placeholders. This replaces two of them, per tier, with values the benchmark supports:

  * probation_min_sessions_per_arm: how many finished sessions each side of a trial needs to detect a 5% cost change
    (the registered ship rule's minimum) at 80% power and a two-sided 5% level, given how much the per-pair cost
    change varied in the benchmark for techniques of that tier: n = 2 (z_0.975 + z_0.8)^2 sd^2 / 0.05^2, clamped to
    [10, 200]. Sessions vary more on a user's own work than on a fixed task suite, so this is a floor, not a promise.
  * test_fail_margin_pts: the success margin the studies registered (5 points in every ship rule so far), so a trial
    holds a technique to the same success rule its benchmark did.

A tier gets numbers only from at least 30 pairs. A tier with less keeps the placeholders in internal/autopilot, and
the file says so. The output is a pure function of the result folders, refused for simulated results and for folders
whose study no longer matches its lock, like `defaults`.
"""

from __future__ import annotations

import csv
import json
import math
import statistics as st
from pathlib import Path

from .study import load_study

Z = 1.959964 + 0.841621          # two-sided 5% level, 80% power
MIN_EFFECT = 0.05                # the ship rule's minimum cost reduction
MIN_PAIRS = 30
CLAMP = (10, 200)

# Tier of each benchmark condition, from the technique registry (internal/technique): T1 safe, T2 behavioural,
# T3 routing. A bundle takes the strictest tier it contains.
T1 = {"noise_normalizer", "duplicate_result_collapser", "output_trimmer", "hook_repeat_read", "hook_read_limit",
      "hook_quiet_commands", "hook_large_output", "hook_output_dedup", "hook_read_outline", "volatile_prefix_mover",
      "cache_breakpoints"}
T2 = {"verbosity_steer"}
T3 = {"model_router", "effort_tool_turns", "effort_routine_prompts", "thinking_clear"}


class ThresholdsError(ValueError):
    pass


def tier_of(condition: str) -> str | None:
    if condition.startswith("alone_"):
        name = condition[len("alone_"):]
        return "T1" if name in T1 else "T2" if name in T2 else "T3" if name in T3 else None
    if condition in ("all_safe", "hooks", "hooks_gateway", "passthrough_plugin") or condition.startswith("profile_"):
        return "T1"
    if condition in ("trove_full", "default_model", "task_cascade", "task_scout"):
        return "T3"
    return None


def _changes(results_dir: Path) -> tuple[str, dict[str, list[float]], float]:
    lock = json.loads((results_dir / "study.lock.json").read_text(encoding="utf-8"))
    versions = json.loads((results_dir / "versions.json").read_text(encoding="utf-8"))
    if versions.get("simulated") or versions.get("fake_agent"):
        raise ThresholdsError(f"{results_dir} comes from simulated or fake-agent runs; thresholds come only from real measurements.")
    study = load_study(results_dir / "config.used.yaml")
    if study.sha256 != lock.get("study_sha256"):
        raise ThresholdsError(f"{results_dir}: the study file no longer matches its lock, so these results are not trusted.")
    out: dict[str, list[float]] = {}
    with open(results_dir / "pairs.csv", encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            tier = tier_of(row["condition"])
            try:
                ref, cond = float(row["reference_cost_usd"]), float(row["condition_cost_usd"])
            except (TypeError, ValueError):
                continue
            if tier and ref > 0:
                out.setdefault(tier, []).append(cond / ref - 1)
    margin = float(study.ship_rule.get("success_margin_pts", 5))
    return f"bench:{study.id}@{lock['study_sha256'][:12]}", out, margin


def generate(result_dirs: list[Path]) -> str:
    by_tier: dict[str, list[float]] = {}
    sources: dict[str, set[str]] = {}
    margins: dict[str, float] = {}
    for d in sorted(result_dirs, key=lambda p: str(p.resolve())):
        src, changes, margin = _changes(d)
        for tier, xs in changes.items():
            by_tier.setdefault(tier, []).extend(xs)
            sources.setdefault(tier, set()).add(src)
            margins[tier] = min(margins.get(tier, margin), margin)
    lines = ["# GENERATED by `python -m trovebench thresholds`. Do not edit by hand. Version 1.",
             "# Autopilot trial thresholds per technique tier, from pre-registered benchmark studies (plan item 10.7).",
             "# A tier that is missing has fewer than 30 benchmark pairs and keeps the placeholders in internal/autopilot.",
             "version = 1"]
    for tier in ("T1", "T2", "T3"):
        xs = by_tier.get(tier, [])
        if len(xs) < MIN_PAIRS:
            lines.append(f"# {tier}: {len(xs)} pairs, fewer than {MIN_PAIRS}; placeholders stay.")
            continue
        sd = st.stdev(xs)
        n = math.ceil(2 * Z * Z * sd * sd / (MIN_EFFECT * MIN_EFFECT))
        n = max(CLAMP[0], min(CLAMP[1], n))
        lines += ["", f"[tiers.{tier}]", f"probation_min_sessions_per_arm = {n}",
                  f"test_fail_margin_pts = {margins[tier]:g}", f"pairs = {len(xs)}",
                  f"cost_change_sd = {round(sd, 6)!r}", f"source = {json.dumps(', '.join(sorted(sources[tier])))}"]
    return "\n".join(lines) + "\n"
